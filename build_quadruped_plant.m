function mdl_path = build_quadruped_plant(model_name)
%BUILD_QUADRUPED_PLANT Programmatically generate quadruped_wbc.slx in Simscape Multibody.
%   mdl_path = BUILD_QUADRUPED_PLANT(model_name) builds the 82.6 kg floating-base
%   quadruped robot (8 actuated leg joints: hip pitch & knee pitch per leg, no
%   hip abduction) equipped with a 6-axis robotic arm and vacuum gripper, along
%   with the ground plane, 10 cm step platform (1.2 m ahead), pick-and-place
%   table with payload box, Spatial Contact Force blocks, and joint sensors.

    if nargin < 1 || isempty(model_name)
        model_name = 'quadruped_wbc';
    end

    p = params();

    load_system('simulink');
    load_system('nesl_utility');
    load_system('sm_lib');

    if bdIsLoaded(model_name)
        close_system(model_name, 0);
    end
    new_system(model_name);

    set_param(model_name, ...
        'Solver', 'ode23t', ...
        'StopTime', '0.5', ...
        'RelTol', '1e-3', ...
        'AbsTol', '1e-4', ...
        'MaxStep', '0.005');

    %% =====================================================================
    %  1. World Frame, Mechanism Configuration, and Solver Configuration
    %  =====================================================================
    b_world  = add_sm_block('sm_lib/Frames and Transforms/World Frame', ...
        [model_name '/World_Frame'], [40, 120, 80, 160]);
    set_param(model_name, 'SimMechanicsOpenEditorOnUpdate', 'off');

    b_mech   = add_sm_block('sm_lib/Utilities/Mechanism Configuration', ...
        [model_name '/Mechanism_Config'], [40, 200, 80, 240], ...
        'GravityVector', sprintf('[0 0 %.4f]', -p.g), ...
        'GravityVectorUnits', 'm/s^2');
    b_solver = add_sm_block('nesl_utility/Solver Configuration', ...
        [model_name '/Solver_Config'], [40, 280, 80, 320]);

    ph_world  = get_param(b_world, 'PortHandles');
    ph_mech   = get_param(b_mech, 'PortHandles');
    ph_solver = get_param(b_solver, 'PortHandles');

    add_line(model_name, ph_world.RConn(1), ph_mech.RConn(1));
    add_line(model_name, ph_world.RConn(1), ph_solver.RConn(1));

    %% =====================================================================
    %  2. Environment & Obstacles (Ground, 10 cm Step, Table, Payload Box)
    %  =====================================================================
    % 2a. Flat Ground Plane (top surface at z = 0)
    ground_thick = 0.10;
    b_rt_ground = add_sm_block('sm_lib/Frames and Transforms/Rigid Transform', ...
        [model_name '/RT_Ground'], [160, 60, 200, 100], ...
        'TranslationMethod', 'Cartesian', ...
        'TranslationCartesianOffset', sprintf('[2.0 0.7 %.4f]', -ground_thick/2));
    b_ground = add_sm_block('sm_lib/Body Elements/Brick Solid', ...
        [model_name '/Ground_Plane'], [250, 60, 290, 100], ...
        'BrickDimensions', sprintf('[10.0 6.0 %.4f]', ground_thick), ...
        'ExportEntireGeometry', 'on', ...
        'GraphicDiffuseColor', '[0.45 0.48 0.52]');

    ph_rt_ground = get_param(b_rt_ground, 'PortHandles');
    ph_ground    = get_param(b_ground, 'PortHandles');
    add_line(model_name, ph_world.RConn(1), ph_rt_ground.LConn(1));
    add_line(model_name, ph_rt_ground.RConn(1), ph_ground.RConn(1));

    % 2b. 10 cm Step Platform located 1.2 m ahead of the robot
    step_height = p.h_step;
    step_depth  = p.x_step_end - p.x_step_start;
    step_width  = p.y_step_max - p.y_step_min;
    step_cx     = 0.5 * (p.x_step_start + p.x_step_end);
    step_cy     = 0.5 * (p.y_step_min   + p.y_step_max);
    b_rt_step = add_sm_block('sm_lib/Frames and Transforms/Rigid Transform', ...
        [model_name '/RT_Step_10cm'], [160, 130, 200, 170], ...
        'TranslationMethod', 'Cartesian', ...
        'TranslationCartesianOffset', ...
        sprintf('[%.4f %.4f %.4f]', step_cx, step_cy, step_height/2));
    b_step = add_sm_block('sm_lib/Body Elements/Brick Solid', ...
        [model_name '/Step_Platform_10cm'], [250, 130, 290, 170], ...
        'BrickDimensions', sprintf('[%.4f %.4f %.4f]', step_depth, step_width, step_height), ...
        'ExportEntireGeometry', 'on', ...
        'GraphicDiffuseColor', '[0.75 0.55 0.25]');

    ph_rt_step = get_param(b_rt_step, 'PortHandles');
    ph_step    = get_param(b_step, 'PortHandles');
    add_line(model_name, ph_world.RConn(1), ph_rt_step.LConn(1));
    add_line(model_name, ph_rt_step.RConn(1), ph_step.RConn(1));

    % 2c. Pick-and-Place Table & Box Payload
    table_h = p.table_height;
    table_x = p.table_center_xy(1);
    table_y = p.table_center_xy(2);
    b_rt_table = add_sm_block('sm_lib/Frames and Transforms/Rigid Transform', ...
        [model_name '/RT_PickPlace_Table'], [160, 200, 200, 240], ...
        'TranslationMethod', 'Cartesian', ...
        'TranslationCartesianOffset', sprintf('[%.4f %.4f %.4f]', table_x, table_y, table_h/2));
    b_table = add_sm_block('sm_lib/Body Elements/Brick Solid', ...
        [model_name '/PickPlace_Table'], [250, 200, 290, 240], ...
        'BrickDimensions', sprintf('[%.4f %.4f %.4f]', p.table_dims(1), p.table_dims(2), table_h), ...
        'ExportEntireGeometry', 'on', ...
        'GraphicDiffuseColor', '[0.35 0.55 0.65]');

    ph_rt_table = get_param(b_rt_table, 'PortHandles');
    ph_table    = get_param(b_table, 'PortHandles');
    add_line(model_name, ph_world.RConn(1), ph_rt_table.LConn(1));
    add_line(model_name, ph_rt_table.RConn(1), ph_table.RConn(1));

    % Floating Box Payload resting on Table (with spherical contact proxy for fast DAE integration)
    box_side = p.box_side;
    box_x0   = p.box_init_pos(1);
    box_y0   = p.box_init_pos(2);
    box_z0   = p.box_init_pos(3);
    b_box_6dof = add_sm_block('sm_lib/Joints/6-DOF Joint', ...
        [model_name '/Payload_6DOF'], [160, 270, 200, 310], ...
        'PxPositionTargetSpecify', 'on', 'PxPositionTargetValue', num2str(box_x0), ...
        'PyPositionTargetSpecify', 'on', 'PyPositionTargetValue', num2str(box_y0), ...
        'PzPositionTargetSpecify', 'on', 'PzPositionTargetValue', num2str(box_z0), ...
        'PxDampingCoefficient', '12', 'PyDampingCoefficient', '12', 'PzDampingCoefficient', '12', ...
        'SphSpringStiffness', '10', 'SphDampingCoefficient', '1');
    b_box = add_sm_block('sm_lib/Body Elements/Brick Solid', ...
        [model_name '/Payload_Box'], [250, 255, 290, 285], ...
        'BrickDimensions', sprintf('[%.4f %.4f %.4f]', box_side, box_side, box_side), ...
        'InertiaType', 'Custom', ...
        'Mass', sprintf('%.4f', p.m_box - 0.05), ...
        'MomentsOfInertia', '[8.0e-4 8.0e-4 8.0e-4]', ...
        'GraphicDiffuseColor', '[0.90 0.25 0.20]');
    b_box_sphere = add_sm_block('sm_lib/Body Elements/Spherical Solid', ...
        [model_name '/Payload_Contact_Sphere'], [250, 295, 290, 325], ...
        'SphereRadius', sprintf('%.4f', box_side/2), ...
        'ExportEntireGeometry', 'on', ...
        'InertiaType', 'Custom', ...
        'Mass', '0.05', ...
        'MomentsOfInertia', '[3.0e-5 3.0e-5 3.0e-5]', ...
        'GraphicOpacity', '0.0');
    b_contact_box = add_sm_block('sm_lib/Forces and Torques/Spatial Contact Force', ...
        [model_name '/Contact_Box_Table'], [340, 235, 380, 275], ...
        'NormalStiffness', num2str(p.k_contact), ...
        'NormalDamping', num2str(p.b_contact), ...
        'NormalTransitionRegionWidth', '1e-3', ...
        'CoefficientOfStaticFriction', num2str(p.mu_static), ...
        'CoefficientOfDynamicFriction', num2str(p.mu_kinetic), ...
        'FrictionalCriticalVelocity', num2str(p.v_transition));

    ph_box_6dof    = get_param(b_box_6dof, 'PortHandles');
    ph_box         = get_param(b_box, 'PortHandles');
    ph_box_sphere  = get_param(b_box_sphere, 'PortHandles');
    ph_contact_box = get_param(b_contact_box, 'PortHandles');
    add_line(model_name, ph_world.RConn(1), ph_box_6dof.LConn(1));
    add_line(model_name, ph_box_6dof.RConn(1), ph_box.RConn(1));
    add_line(model_name, ph_box_6dof.RConn(1), ph_box_sphere.RConn(1));
    add_line(model_name, ph_table.LConn(1), ph_contact_box.LConn(1));
    add_line(model_name, ph_box_sphere.LConn(1), ph_contact_box.RConn(1));

    %% =====================================================================
    %  3. Floating-Base Quadruped Torso (6-DOF Joint + 50.0 kg Trunk Solid)
    %  =====================================================================
    z_init = p.z_nom + p.r_foot;
    b_torso_6dof = add_sm_block('sm_lib/Joints/6-DOF Joint', ...
        [model_name '/Torso_6DOF'], [160, 420, 210, 480], ...
        'PxPositionTargetSpecify', 'on', 'PxPositionTargetValue', '0', ...
        'PyPositionTargetSpecify', 'on', 'PyPositionTargetValue', '0', ...
        'PzPositionTargetSpecify', 'on', 'PzPositionTargetValue', sprintf('%.8f', z_init), ...
        'PxSensePosition', 'on', 'PxSenseVelocity', 'on', ...
        'PySensePosition', 'on', 'PySenseVelocity', 'on', ...
        'PzSensePosition', 'on', 'PzSenseVelocity', 'on');

    I_trunk_diag = [p.I_body(1,1), p.I_body(2,2), p.I_body(3,3)];
    b_trunk = add_sm_block('sm_lib/Body Elements/Brick Solid', ...
        [model_name '/Trunk_Solid'], [270, 420, 320, 480], ...
        'BrickDimensions', sprintf('[%.4f %.4f 0.18]', p.L_body, p.W_body), ...
        'InertiaType', 'Custom', ...
        'Mass', sprintf('%.4f', p.m_trunk), ...
        'CenterOfMass', mat2str(p.trunk_com_offset.'), ...
        'MomentsOfInertia', mat2str(I_trunk_diag), ...
        'GraphicDiffuseColor', '[0.20 0.25 0.32]');

    ph_torso_6dof = get_param(b_torso_6dof, 'PortHandles');
    ph_trunk      = get_param(b_trunk, 'PortHandles');
    add_line(model_name, ph_world.RConn(1), ph_torso_6dof.LConn(1));
    add_line(model_name, ph_torso_6dof.RConn(1), ph_trunk.RConn(1));

    b_mux_p = add_sm_block('simulink/Commonly Used Blocks/Mux', ...
        [model_name '/Mux_Torso_Pos'], [320, 350, 325, 395], 'Inputs', '3');
    b_mux_v = add_sm_block('simulink/Commonly Used Blocks/Mux', ...
        [model_name '/Mux_Torso_Vel'], [320, 500, 325, 545], 'Inputs', '3');
    ph_mux_p = get_param(b_mux_p, 'PortHandles');
    ph_mux_v = get_param(b_mux_v, 'PortHandles');

    for axis_idx = 1:3
        b_ps_p = add_sm_block('nesl_utility/PS-Simulink Converter', ...
            sprintf('%s/PS2SL_Torso_P%d', model_name, axis_idx), [245, 330 + 20*axis_idx, 265, 345 + 20*axis_idx]);
        b_ps_v = add_sm_block('nesl_utility/PS-Simulink Converter', ...
            sprintf('%s/PS2SL_Torso_V%d', model_name, axis_idx), [245, 480 + 20*axis_idx, 265, 495 + 20*axis_idx]);
        ph_ps_p = get_param(b_ps_p, 'PortHandles');
        ph_ps_v = get_param(b_ps_v, 'PortHandles');

        add_line(model_name, ph_torso_6dof.RConn(2*axis_idx),     ph_ps_p.LConn(1));
        add_line(model_name, ph_torso_6dof.RConn(2*axis_idx + 1), ph_ps_v.LConn(1));
        add_line(model_name, ph_ps_p.Outport(1), ph_mux_p.Inport(axis_idx));
        add_line(model_name, ph_ps_v.Outport(1), ph_mux_v.Inport(axis_idx));
    end

    b_out_p = add_sm_block('simulink/Sinks/To Workspace', ...
        [model_name '/ToWS_Torso_Pos'], [360, 360, 420, 385], ...
        'VariableName', 'sim_torso_pos', 'SaveFormat', 'Timeseries');
    b_out_v = add_sm_block('simulink/Sinks/To Workspace', ...
        [model_name '/ToWS_Torso_Vel'], [360, 510, 420, 535], ...
        'VariableName', 'sim_torso_vel', 'SaveFormat', 'Timeseries');
    add_line(model_name, ph_mux_p.Outport(1), get_param(b_out_p, 'PortHandles').Inport(1));
    add_line(model_name, ph_mux_v.Outport(1), get_param(b_out_v, 'PortHandles').Inport(1));

    %% =====================================================================
    %  4. Four 2-DOF Legs (FL, FR, RL, RR): Hip Pitch & Knee Pitch + Contacts
    %  =====================================================================
    [tau_nom_legs, ~] = vmc_stance_controller([], [], [1; 1; 1; 1], repmat(p.q_leg_nom, 1, 4), p);
    Kp_joint_lock = 1500.0;
    Kd_joint_lock = 80.0;

    b_mux_q = add_sm_block('simulink/Commonly Used Blocks/Mux', ...
        [model_name '/Mux_Leg_Angles'], [1050, 380, 1055, 540], 'Inputs', '8');
    b_mux_w = add_sm_block('simulink/Commonly Used Blocks/Mux', ...
        [model_name '/Mux_Leg_Vels'], [1050, 560, 1055, 720], 'Inputs', '8');
    ph_mux_q = get_param(b_mux_q, 'PortHandles');
    ph_mux_w = get_param(b_mux_w, 'PortHandles');

    m_foot_sphere = 0.10;
    m_shank_body  = p.m_shank - m_foot_sphere;

    for i = 1:4
        leg_tag = p.leg_names{i};
        y_row = 40 + (i - 1) * 190;
        hip_xyz = p.hip_offsets(:, i);

        b_rt_hip = add_sm_block('sm_lib/Frames and Transforms/Rigid Transform', ...
            sprintf('%s/RT_Hip_%s', model_name, leg_tag), [450, y_row, 485, y_row + 35], ...
            'TranslationMethod', 'Cartesian', ...
            'TranslationCartesianOffset', sprintf('[%.6f %.6f %.6f]', hip_xyz(1), hip_xyz(2), hip_xyz(3)), ...
            'RotationMethod', 'AlignedAxes', ...
            'FollAlignAxisA', '+Z', 'BaseAlignAxisA', '+Y', ...
            'FollAlignAxisB', '+Y', 'BaseAlignAxisB', '-Z');

        b_hip = add_sm_block('sm_lib/Joints/Revolute Joint', ...
            sprintf('%s/HipPitch_%s', model_name, leg_tag), [520, y_row, 560, y_row + 45], ...
            'TorqueActuationMode', 'InputTorque', ...
            'MotionActuationMode', 'ComputedMotion', ...
            'SensePosition', 'on', ...
            'SenseVelocity', 'on', ...
            'PositionTargetSpecify', 'on', ...
            'PositionTargetPriority', 'High', ...
            'PositionTargetValueUnits', 'rad', ...
            'PositionTargetValue', sprintf('%.10f', p.q_hip_nom), ...
            'EquilibriumPositionUnits', 'rad', ...
            'EquilibriumPosition', sprintf('%.10f', p.q_hip_nom), ...
            'SpringStiffnessUnits', 'N*m/rad', ...
            'SpringStiffness', sprintf('%.4f', Kp_joint_lock), ...
            'DampingCoefficientUnits', 'N*m/(rad/s)', ...
            'DampingCoefficient', sprintf('%.4f', Kd_joint_lock));

        b_rt_thigh_com = add_sm_block('sm_lib/Frames and Transforms/Rigid Transform', ...
            sprintf('%s/RT_ThighCoM_%s', model_name, leg_tag), [595, y_row - 30, 625, y_row], ...
            'TranslationMethod', 'Cartesian', ...
            'TranslationCartesianOffset', sprintf('[0 %.6f 0]', p.L_thigh / 2));
        b_thigh = add_sm_block('sm_lib/Body Elements/Brick Solid', ...
            sprintf('%s/ThighSolid_%s', model_name, leg_tag), [650, y_row - 30, 685, y_row], ...
            'BrickDimensions', sprintf('[0.06 %.4f 0.06]', p.L_thigh), ...
            'InertiaType', 'Custom', ...
            'Mass', sprintf('%.4f', p.m_thigh), ...
            'MomentsOfInertia', sprintf('[%.4f 0.004 %.4f]', p.I_thigh_yy, p.I_thigh_yy), ...
            'GraphicDiffuseColor', '[0.30 0.55 0.80]');

        b_rt_knee = add_sm_block('sm_lib/Frames and Transforms/Rigid Transform', ...
            sprintf('%s/RT_Knee_%s', model_name, leg_tag), [595, y_row + 15, 625, y_row + 45], ...
            'TranslationMethod', 'Cartesian', ...
            'TranslationCartesianOffset', sprintf('[0 %.6f 0]', p.L_thigh));

        b_knee = add_sm_block('sm_lib/Joints/Revolute Joint', ...
            sprintf('%s/KneePitch_%s', model_name, leg_tag), [710, y_row + 15, 750, y_row + 60], ...
            'TorqueActuationMode', 'InputTorque', ...
            'MotionActuationMode', 'ComputedMotion', ...
            'SensePosition', 'on', ...
            'SenseVelocity', 'on', ...
            'PositionTargetSpecify', 'on', ...
            'PositionTargetPriority', 'High', ...
            'PositionTargetValueUnits', 'rad', ...
            'PositionTargetValue', sprintf('%.10f', p.q_knee_nom), ...
            'EquilibriumPositionUnits', 'rad', ...
            'EquilibriumPosition', sprintf('%.10f', p.q_knee_nom), ...
            'SpringStiffnessUnits', 'N*m/rad', ...
            'SpringStiffness', sprintf('%.4f', Kp_joint_lock), ...
            'DampingCoefficientUnits', 'N*m/(rad/s)', ...
            'DampingCoefficient', sprintf('%.4f', Kd_joint_lock));

        b_rt_shank_com = add_sm_block('sm_lib/Frames and Transforms/Rigid Transform', ...
            sprintf('%s/RT_ShankCoM_%s', model_name, leg_tag), [785, y_row - 20, 815, y_row + 10], ...
            'TranslationMethod', 'Cartesian', ...
            'TranslationCartesianOffset', sprintf('[0 %.6f 0]', p.L_shank / 2));
        b_shank = add_sm_block('sm_lib/Body Elements/Brick Solid', ...
            sprintf('%s/ShankSolid_%s', model_name, leg_tag), [840, y_row - 20, 875, y_row + 10], ...
            'BrickDimensions', sprintf('[0.045 %.4f 0.045]', p.L_shank), ...
            'InertiaType', 'Custom', ...
            'Mass', sprintf('%.4f', m_shank_body), ...
            'MomentsOfInertia', sprintf('[%.4f 0.002 %.4f]', p.I_shank_yy, p.I_shank_yy), ...
            'GraphicDiffuseColor', '[0.75 0.78 0.82]');

        b_rt_foot = add_sm_block('sm_lib/Frames and Transforms/Rigid Transform', ...
            sprintf('%s/RT_Foot_%s', model_name, leg_tag), [785, y_row + 25, 815, y_row + 55], ...
            'TranslationMethod', 'Cartesian', ...
            'TranslationCartesianOffset', sprintf('[0 %.6f 0]', p.L_shank));
        b_foot = add_sm_block('sm_lib/Body Elements/Spherical Solid', ...
            sprintf('%s/FootSphere_%s', model_name, leg_tag), [840, y_row + 25, 875, y_row + 55], ...
            'SphereRadius', sprintf('%.4f', p.r_foot), ...
            'ExportEntireGeometry', 'on', ...
            'InertiaType', 'Custom', ...
            'Mass', sprintf('%.4f', m_foot_sphere), ...
            'MomentsOfInertia', '[1e-4 1e-4 1e-4]', ...
            'GraphicDiffuseColor', '[0.15 0.15 0.15]');

        ph_rt_hip   = get_param(b_rt_hip, 'PortHandles');
        ph_hip      = get_param(b_hip, 'PortHandles');
        ph_rt_tcom  = get_param(b_rt_thigh_com, 'PortHandles');
        ph_thigh    = get_param(b_thigh, 'PortHandles');
        ph_rt_knee  = get_param(b_rt_knee, 'PortHandles');
        ph_knee     = get_param(b_knee, 'PortHandles');
        ph_rt_scom  = get_param(b_rt_shank_com, 'PortHandles');
        ph_shank    = get_param(b_shank, 'PortHandles');
        ph_rt_foot  = get_param(b_rt_foot, 'PortHandles');
        ph_foot     = get_param(b_foot, 'PortHandles');

        add_line(model_name, ph_trunk.RConn(1), ph_rt_hip.LConn(1));
        add_line(model_name, ph_rt_hip.RConn(1), ph_hip.LConn(1));
        add_line(model_name, ph_hip.RConn(1), ph_rt_tcom.LConn(1));
        add_line(model_name, ph_rt_tcom.RConn(1), ph_thigh.RConn(1));
        add_line(model_name, ph_hip.RConn(1), ph_rt_knee.LConn(1));
        add_line(model_name, ph_rt_knee.RConn(1), ph_knee.LConn(1));
        add_line(model_name, ph_knee.RConn(1), ph_rt_scom.LConn(1));
        add_line(model_name, ph_rt_scom.RConn(1), ph_shank.RConn(1));
        add_line(model_name, ph_knee.RConn(1), ph_rt_foot.LConn(1));
        add_line(model_name, ph_rt_foot.RConn(1), ph_foot.RConn(1));

        b_c_gnd = add_sm_block('sm_lib/Forces and Torques/Spatial Contact Force', ...
            sprintf('%s/Contact_FootGround_%s', model_name, leg_tag), [920, y_row + 10, 955, y_row + 40], ...
            'NormalStiffness', num2str(p.k_contact), ...
            'NormalDamping', num2str(p.b_contact), ...
            'NormalTransitionRegionWidth', '1e-3', ...
            'CoefficientOfStaticFriction', num2str(p.mu_static), ...
            'CoefficientOfDynamicFriction', num2str(p.mu_kinetic), ...
            'FrictionalCriticalVelocity', num2str(p.v_transition));
        b_c_stp = add_sm_block('sm_lib/Forces and Torques/Spatial Contact Force', ...
            sprintf('%s/Contact_FootStep_%s', model_name, leg_tag), [920, y_row + 50, 955, y_row + 80], ...
            'NormalStiffness', num2str(p.k_contact), ...
            'NormalDamping', num2str(p.b_contact), ...
            'NormalTransitionRegionWidth', '1e-3', ...
            'CoefficientOfStaticFriction', num2str(p.mu_static), ...
            'CoefficientOfDynamicFriction', num2str(p.mu_kinetic), ...
            'FrictionalCriticalVelocity', num2str(p.v_transition));

        ph_c_gnd = get_param(b_c_gnd, 'PortHandles');
        ph_c_stp = get_param(b_c_stp, 'PortHandles');
        add_line(model_name, ph_ground.LConn(1), ph_c_gnd.LConn(1));
        add_line(model_name, ph_foot.LConn(1),   ph_c_gnd.RConn(1));
        add_line(model_name, ph_step.LConn(1),   ph_c_stp.LConn(1));
        add_line(model_name, ph_foot.LConn(1),   ph_c_stp.RConn(1));

        [q_hip_out, w_hip_out] = wire_joint_actuation_and_sensing(model_name, ...
            sprintf('Hip_%s', leg_tag), ph_hip, tau_nom_legs(1, i), [500, y_row + 65]);
        [q_knee_out, w_knee_out] = wire_joint_actuation_and_sensing(model_name, ...
            sprintf('Knee_%s', leg_tag), ph_knee, tau_nom_legs(2, i), [700, y_row + 75]);

        add_line(model_name, q_hip_out,  ph_mux_q.Inport(2*i - 1));
        add_line(model_name, q_knee_out, ph_mux_q.Inport(2*i));
        add_line(model_name, w_hip_out,  ph_mux_w.Inport(2*i - 1));
        add_line(model_name, w_knee_out, ph_mux_w.Inport(2*i));
    end

    b_out_q = add_sm_block('simulink/Sinks/To Workspace', ...
        [model_name '/ToWS_Leg_Angles'], [1085, 445, 1145, 475], ...
        'VariableName', 'sim_q_legs', 'SaveFormat', 'Timeseries');
    b_out_w = add_sm_block('simulink/Sinks/To Workspace', ...
        [model_name '/ToWS_Leg_Vels'], [1085, 625, 1145, 655], ...
        'VariableName', 'sim_dq_legs', 'SaveFormat', 'Timeseries');
    add_line(model_name, ph_mux_q.Outport(1), get_param(b_out_q, 'PortHandles').Inport(1));
    add_line(model_name, ph_mux_w.Outport(1), get_param(b_out_w, 'PortHandles').Inport(1));

    %% =====================================================================
    %  5. 6-Axis Robotic Arm (12.0 kg) & Vacuum Gripper (1.4 kg) on Front Trunk
    %  =====================================================================
    b_rt_arm_base = add_sm_block('sm_lib/Frames and Transforms/Rigid Transform', ...
        [model_name '/RT_Arm_Base'], [450, 820, 485, 855], ...
        'TranslationMethod', 'Cartesian', ...
        'TranslationCartesianOffset', ...
        sprintf('[%.4f %.4f %.4f]', p.arm_base_offset(1), p.arm_base_offset(2), p.arm_base_offset(3)));
    ph_arm_prev = get_param(b_rt_arm_base, 'PortHandles').RConn(1);
    add_line(model_name, ph_trunk.RConn(1), get_param(b_rt_arm_base, 'PortHandles').LConn(1));

    arm_link_lengths = p.arm_link_lengths;
    arm_q_init       = p.q_arm_stow;
    arm_colors       = {'[0.85 0.45 0.15]', '[0.25 0.30 0.35]', '[0.85 0.45 0.15]', ...
                        '[0.25 0.30 0.35]', '[0.85 0.45 0.15]', '[0.25 0.30 0.35]'};

    for j = 1:6
        x_col = 515 + (j - 1) * 95;
        b_aj = add_sm_block('sm_lib/Joints/Revolute Joint', ...
            sprintf('%s/ArmJoint_%d', model_name, j), [x_col, 820, x_col + 35, 855], ...
            'PositionTargetSpecify', 'on', ...
            'PositionTargetValueUnits', 'rad', ...
            'PositionTargetValue', sprintf('%.6f', arm_q_init(j)), ...
            'EquilibriumPositionUnits', 'rad', ...
            'EquilibriumPosition', sprintf('%.6f', arm_q_init(j)), ...
            'SpringStiffnessUnits', 'N*m/rad', ...
            'SpringStiffness', '500', ...
            'DampingCoefficientUnits', 'N*m/(rad/s)', ...
            'DampingCoefficient', '30');
        b_alink = add_sm_block('sm_lib/Body Elements/Brick Solid', ...
            sprintf('%s/ArmLink_%d', model_name, j), [x_col, 875, x_col + 35, 905], ...
            'BrickDimensions', sprintf('[0.05 0.05 %.4f]', arm_link_lengths(j)), ...
            'InertiaType', 'Custom', ...
            'Mass', sprintf('%.4f', p.m_arm_links(j)), ...
            'MomentsOfInertia', '[0.008 0.008 0.004]', ...
            'GraphicDiffuseColor', arm_colors{j});
        b_rt_next = add_sm_block('sm_lib/Frames and Transforms/Rigid Transform', ...
            sprintf('%s/RT_ArmNext_%d', model_name, j), [x_col + 45, 820, x_col + 75, 850], ...
            'TranslationMethod', 'Cartesian', ...
            'TranslationCartesianOffset', sprintf('[0 0 %.4f]', arm_link_lengths(j)));

        ph_aj   = get_param(b_aj, 'PortHandles');
        ph_al   = get_param(b_alink, 'PortHandles');
        ph_next = get_param(b_rt_next, 'PortHandles');

        add_line(model_name, ph_arm_prev, ph_aj.LConn(1));
        add_line(model_name, ph_aj.RConn(1), ph_al.RConn(1));
        add_line(model_name, ph_aj.RConn(1), ph_next.LConn(1));
        ph_arm_prev = ph_next.RConn(1);
    end

    % Vacuum Gripper Solid (1.30 kg housing + 0.10 kg suction cup tip = 1.40 kg) & End-Effector Frame
    b_gripper = add_sm_block('sm_lib/Body Elements/Brick Solid', ...
        [model_name '/Vacuum_Gripper_Solid'], [1100, 820, 1140, 855], ...
        'BrickDimensions', '[0.07 0.07 0.05]', ...
        'InertiaType', 'Custom', ...
        'Mass', sprintf('%.4f', p.m_gripper - 0.10), ...
        'MomentsOfInertia', '[0.0018 0.0018 0.0018]', ...
        'GraphicDiffuseColor', '[0.10 0.70 0.45]');
    b_ee_frame = add_sm_block('sm_lib/Frames and Transforms/Rigid Transform', ...
        [model_name '/Vacuum_EE_Frame'], [1100, 875, 1140, 905], ...
        'TranslationMethod', 'Cartesian', ...
        'TranslationCartesianOffset', sprintf('[0 0 %.4f]', p.arm_ee_offset));
    b_ee_cup = add_sm_block('sm_lib/Body Elements/Spherical Solid', ...
        [model_name '/Vacuum_Suction_Cup'], [1165, 875, 1200, 905], ...
        'SphereRadius', '0.020', ...
        'InertiaType', 'Custom', ...
        'Mass', '0.10', ...
        'MomentsOfInertia', '[2e-4 2e-4 2e-4]', ...
        'GraphicDiffuseColor', '[0.15 0.15 0.15]');

    add_line(model_name, ph_arm_prev, get_param(b_gripper, 'PortHandles').RConn(1));
    add_line(model_name, ph_arm_prev, get_param(b_ee_frame, 'PortHandles').LConn(1));
    add_line(model_name, get_param(b_ee_frame, 'PortHandles').RConn(1), ...
        get_param(b_ee_cup, 'PortHandles').RConn(1));

    %% =====================================================================
    %  6. Save Model (.slx)
    %  =====================================================================
    mdl_path = fullfile(pwd, [model_name '.slx']);
    save_system(model_name, mdl_path);
    fprintf('Successfully built and saved Simscape Multibody plant: %s\n', mdl_path);
end

%% ---------------- Local Helper Functions ----------------

function blk = add_sm_block(lib_path, dest_path, pos, varargin)
    blk = add_block(lib_path, dest_path, 'Position', pos, varargin{:});
end

function [q_out_port, w_out_port] = wire_joint_actuation_and_sensing(mdl, tag, ph_joint, tau_ff, xy)
    x0 = xy(1);
    y0 = xy(2);

    b_ff = add_block('simulink/Sources/Constant', ...
        sprintf('%s/tauff_%s', mdl, tag), 'Position', [x0, y0, x0+25, y0+15], ...
        'Value', sprintf('%.10f', tau_ff));
    b_sl2ps = add_block('nesl_utility/Simulink-PS Converter', ...
        sprintf('%s/SL2PS_tau_%s', mdl, tag), 'Position', [x0+35, y0, x0+55, y0+15]);

    b_ps_q = add_block('nesl_utility/PS-Simulink Converter', ...
        sprintf('%s/PS2SL_q_%s', mdl, tag), 'Position', [x0, y0+25, x0+20, y0+40]);
    b_ps_w = add_block('nesl_utility/PS-Simulink Converter', ...
        sprintf('%s/PS2SL_w_%s', mdl, tag), 'Position', [x0, y0+45, x0+20, y0+60]);

    ph_ff    = get_param(b_ff, 'PortHandles');
    ph_sl2ps = get_param(b_sl2ps, 'PortHandles');
    ph_ps_q  = get_param(b_ps_q, 'PortHandles');
    ph_ps_w  = get_param(b_ps_w, 'PortHandles');

    add_line(mdl, ph_ff.Outport(1),  ph_sl2ps.Inport(1));
    add_line(mdl, ph_sl2ps.RConn(1), ph_joint.LConn(2));
    add_line(mdl, ph_joint.RConn(2), ph_ps_q.LConn(1));
    add_line(mdl, ph_joint.RConn(3), ph_ps_w.LConn(1));

    q_out_port = ph_ps_q.Outport(1);
    w_out_port = ph_ps_w.Outport(1);
end
