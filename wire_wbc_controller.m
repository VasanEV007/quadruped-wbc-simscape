function mdl_path = wire_wbc_controller(model_name, gait_mode_default)
%WIRE_WBC_CONTROLLER Programmatically wire the Stage 3/4/5 closed-loop WBC into quadruped_wbc.slx.
%   mdl_path = WIRE_WBC_CONTROLLER(model_name, gait_mode_default) builds/updates
%   quadruped_wbc.slx by adding the Simulink MATLAB Function block (WBC_Controller)
%   configured via Stateflow.EMChart, connecting the 6-DOF base sensors, 8 leg
%   joint sensors, and 6-DOF payload box sensors, wiring the leg joint torques,
%   torso guidance wrench, and vacuum gripper suction attraction force, and
%   logging full telemetry to workspace.

if nargin < 1 || isempty(model_name)
    model_name = 'quadruped_wbc';
end
if nargin < 2 || isempty(gait_mode_default)
    gait_mode_default = 0; % 0=Stand, 1=Trot, 2=Stage 4 Course, 3=Stage 5 Full 22.4s Mission
end

p = params();

% Start from a clean Stage 2 plant build
mdl_path = build_quadruped_plant(model_name);
load_system(model_name);
set_param(model_name, 'SimMechanicsOpenEditorOnUpdate', 'off');

%% =====================================================================
%  1. Enable Spherical Orientation/Velocity Sensing & Wrench Ports on Torso_6DOF
%  =====================================================================
b_torso_6dof = [model_name '/Torso_6DOF'];
set_param(b_torso_6dof, ...
    'PxTorqueActuationMode', 'InputTorque', ...
    'PyTorqueActuationMode', 'InputTorque', ...
    'PzTorqueActuationMode', 'InputTorque', ...
    'SphTorqueActuationMode', 'InputTorque', ...
    'SphActuateTorque', 'on', ...
    'SphActuationFrame', 'BaseFrame', ...
    'SphSensePosition', 'on', ...
    'SphSenseVelocity', 'on', ...
    'SphSensingFrame', 'BaseFrame');

ph_torso_6dof = get_param(b_torso_6dof, 'PortHandles');

b_ps_quat = add_block('nesl_utility/PS-Simulink Converter', ...
    [model_name '/PS2SL_Torso_Quat'], 'Position', [245, 560, 265, 575]);
b_ps_omega = add_block('nesl_utility/PS-Simulink Converter', ...
    [model_name '/PS2SL_Torso_Omega'], 'Position', [245, 590, 265, 605]);

ph_ps_quat  = get_param(b_ps_quat, 'PortHandles');
ph_ps_omega = get_param(b_ps_omega, 'PortHandles');

add_line(model_name, ph_torso_6dof.RConn(8), ph_ps_quat.LConn(1));
add_line(model_name, ph_torso_6dof.RConn(9), ph_ps_omega.LConn(1));

%% =====================================================================
%  2. Enable 3D Position/Velocity Sensing & Vacuum Suction Actuation on Payload_6DOF
%  =====================================================================
b_box_6dof = [model_name '/Payload_6DOF'];
set_param(b_box_6dof, ...
    'PxTorqueActuationMode', 'InputTorque', ...
    'PyTorqueActuationMode', 'InputTorque', ...
    'PzTorqueActuationMode', 'InputTorque', ...
    'PxSensePosition', 'on', 'PxSenseVelocity', 'on', ...
    'PySensePosition', 'on', 'PySenseVelocity', 'on', ...
    'PzSensePosition', 'on', 'PzSenseVelocity', 'on');

ph_box_6dof = get_param(b_box_6dof, 'PortHandles');

b_mux_box_p = add_block('simulink/Commonly Used Blocks/Mux', ...
    [model_name '/Mux_Box_Pos'], 'Position', [320, 285, 325, 325], 'Inputs', '3');
b_mux_box_v = add_block('simulink/Commonly Used Blocks/Mux', ...
    [model_name '/Mux_Box_Vel'], 'Position', [320, 330, 325, 370], 'Inputs', '3');
ph_mux_box_p = get_param(b_mux_box_p, 'PortHandles');
ph_mux_box_v = get_param(b_mux_box_v, 'PortHandles');

for axis_idx = 1:3
    b_ps_bp = add_block('nesl_utility/PS-Simulink Converter', ...
        sprintf('%s/PS2SL_Box_P%d', model_name, axis_idx), ...
        'Position', [215, 270 + 15*axis_idx, 230, 282 + 15*axis_idx]);
    b_ps_bv = add_block('nesl_utility/PS-Simulink Converter', ...
        sprintf('%s/PS2SL_Box_V%d', model_name, axis_idx), ...
        'Position', [215, 315 + 15*axis_idx, 230, 327 + 15*axis_idx]);
    ph_ps_bp = get_param(b_ps_bp, 'PortHandles');
    ph_ps_bv = get_param(b_ps_bv, 'PortHandles');

    add_line(model_name, ph_box_6dof.RConn(2*axis_idx),     ph_ps_bp.LConn(1));
    add_line(model_name, ph_box_6dof.RConn(2*axis_idx + 1), ph_ps_bv.LConn(1));
    add_line(model_name, ph_ps_bp.Outport(1), ph_mux_box_p.Inport(axis_idx));
    add_line(model_name, ph_ps_bv.Outport(1), ph_mux_box_v.Inport(axis_idx));
end

b_out_box_p = add_block('simulink/Sinks/To Workspace', ...
    [model_name '/ToWS_Box_Pos'], 'Position', [360, 292, 420, 318], ...
    'VariableName', 'sim_box_pos', 'SaveFormat', 'Timeseries');
add_line(model_name, ph_mux_box_p.Outport(1), get_param(b_out_box_p, 'PortHandles').Inport(1));

%% =====================================================================
%  3. Configure 8 Leg Revolute Joints for Active Closed-Loop Torque Control
%  =====================================================================
sl2ps_tau_handles = zeros(8, 1);

for i = 1:4
    leg_tag = p.leg_names{i};
    joint_tags = {sprintf('Hip_%s', leg_tag), sprintf('Knee_%s', leg_tag)};
    rev_blocks = {sprintf('%s/HipPitch_%s', model_name, leg_tag), ...
        sprintf('%s/KneePitch_%s', model_name, leg_tag)};

    for j = 1:2
        idx = 2*i - (2 - j);
        jtag = joint_tags{j};
        b_rev = rev_blocks{j};

        set_param(b_rev, ...
            'SpringStiffness', '0', ...
            'DampingCoefficientUnits', 'N*m/(rad/s)', ...
            'DampingCoefficient', '6.0');

        b_ff = sprintf('%s/tauff_%s', model_name, jtag);
        b_sl2ps = sprintf('%s/SL2PS_tau_%s', model_name, jtag);

        ph_sl2ps = get_param(b_sl2ps, 'PortHandles');
        line_in = get_param(ph_sl2ps.Inport(1), 'Line');
        if line_in ~= -1
            delete_line(line_in);
        end
        if getSimulinkBlockHandle(b_ff) ~= -1
            delete_block(b_ff);
        end

        set_param(b_sl2ps, ...
            'FilteringAndDerivatives', 'filter', ...
            'SimscapeFilterOrder', '1', ...
            'InputFilterTimeConstant', '0.001');

        sl2ps_tau_handles(idx) = ph_sl2ps.Inport(1);
    end
end

%% =====================================================================
%  4. Add Clock, Gait Mode Command, ZOH Samplers, and MATLAB Function Block
%  =====================================================================
ctrl_dt = '0.001'; % 1 kHz real-time digital WBC update rate

b_clock = add_block('simulink/Sources/Clock', ...
    [model_name '/Sim_Clock'], 'Position', [1180, 100, 1205, 120]);
b_gmode = add_block('simulink/Sources/Constant', ...
    [model_name '/Gait_Mode_Cmd'], 'Position', [1180, 450, 1210, 470], ...
    'Value', num2str(gait_mode_default));

zoh_names = {'ZOH_t', 'ZOH_p', 'ZOH_v', 'ZOH_quat', 'ZOH_omega', ...
    'ZOH_q', 'ZOH_dq', 'ZOH_mode', 'ZOH_box_p', 'ZOH_box_v'};
src_ports = [ ...
    get_param(b_clock, 'PortHandles').Outport(1); ...
    get_param([model_name '/Mux_Torso_Pos'], 'PortHandles').Outport(1); ...
    get_param([model_name '/Mux_Torso_Vel'], 'PortHandles').Outport(1); ...
    ph_ps_quat.Outport(1); ...
    ph_ps_omega.Outport(1); ...
    get_param([model_name '/Mux_Leg_Angles'], 'PortHandles').Outport(1); ...
    get_param([model_name '/Mux_Leg_Vels'], 'PortHandles').Outport(1); ...
    get_param(b_gmode, 'PortHandles').Outport(1); ...
    ph_mux_box_p.Outport(1); ...
    ph_mux_box_v.Outport(1) ...
    ];

zoh_out_ports = zeros(10, 1);
for k = 1:10
    y_pos = 100 + (k - 1) * 48;
    b_zoh = add_block('simulink/Discrete/Zero-Order Hold', ...
        sprintf('%s/%s', model_name, zoh_names{k}), ...
        'Position', [1245, y_pos, 1275, y_pos + 22], ...
        'SampleTime', ctrl_dt);
    ph_zoh = get_param(b_zoh, 'PortHandles');
    add_line(model_name, src_ports(k), ph_zoh.Inport(1));
    zoh_out_ports(k) = ph_zoh.Outport(1);
end

wbc_blk_path = [model_name '/WBC_Controller'];
b_wbc = add_block('simulink/User-Defined Functions/MATLAB Function', ...
    wbc_blk_path, ...
    'Position', [1320, 100, 1485, 620]);

wbc_script = sprintf([ ...
    'function [tau_legs, tau_arm, rpy, F_grf, contact_mask, nav_log, wrench_assist, F_suction, q_arm, w_arm, mission_log] = ...\n' ...
    '    wbc_control_fcn(t, p_com, v_com, quat_wb, omega_w, q_legs, dq_legs, gait_mode, p_box, v_box)\n' ...
    '%%WBC_CONTROL_FCN Closed-loop VMC + Raibert + Pure-Pursuit + 6-Axis Arm Pick-and-Place.\n' ...
    'coder.extrinsic(''wbc_step'');\n' ...
    'tau_legs      = zeros(8, 1);\n' ...
    'tau_arm       = zeros(6, 1);\n' ...
    'rpy           = zeros(3, 1);\n' ...
    'F_grf         = zeros(12, 1);\n' ...
    'contact_mask  = ones(4, 1);\n' ...
    'nav_log       = zeros(12, 1);\n' ...
    'wrench_assist = zeros(6, 1);\n' ...
    'F_suction     = zeros(3, 1);\n' ...
    'q_arm         = zeros(6, 1);\n' ...
    'w_arm         = zeros(6, 1);\n' ...
    'mission_log   = zeros(8, 1);\n' ...
    '[tau_legs, tau_arm, rpy, F_grf, contact_mask, nav_log, wrench_assist, F_suction, q_arm, w_arm, mission_log] = ...\n' ...
    '    wbc_step(t, p_com, v_com, quat_wb, omega_w, q_legs, dq_legs, gait_mode, p_box, v_box);\n' ...
    'end\n']);

rt = sfroot;
em_chart = rt.find('-isa', 'Stateflow.EMChart', 'Path', wbc_blk_path);
if isempty(em_chart)
    error('wire_wbc_controller:EMChartNotFound', ...
        'Could not locate Stateflow.EMChart for WBC_Controller.');
end
em_chart.Script = wbc_script;

ph_wbc = get_param(b_wbc, 'PortHandles');
for k = 1:10
    add_line(model_name, zoh_out_ports(k), ph_wbc.Inport(k));
end

%% =====================================================================
%  5. Demux Leg Torques, Torso Guidance Wrench & Vacuum Suction Force
%  =====================================================================
b_demux_tau = add_block('simulink/Commonly Used Blocks/Demux', ...
    [model_name '/Demux_Leg_Torques'], ...
    'Position', [1530, 100, 1535, 240], ...
    'Outputs', '8');
ph_demux_tau = get_param(b_demux_tau, 'PortHandles');
add_line(model_name, ph_wbc.Outport(1), ph_demux_tau.Inport(1));

for idx = 1:8
    add_line(model_name, ph_demux_tau.Outport(idx), sl2ps_tau_handles(idx));
end

% Demux 6D Torso Assist Wrench into [Fx (1), Fy (1), Fz (1), T_xyz (3)]
b_demux_w = add_block('simulink/Commonly Used Blocks/Demux', ...
    [model_name '/Demux_Torso_Wrench'], ...
    'Position', [1530, 520, 1535, 610], ...
    'Outputs', '[1 1 1 3]');
ph_demux_w = get_param(b_demux_w, 'PortHandles');
add_line(model_name, ph_wbc.Outport(7), ph_demux_w.Inport(1));

for w_idx = 1:4
    b_sl2ps_w = add_block('nesl_utility/Simulink-PS Converter', ...
        sprintf('%s/SL2PS_TorsoWrench_%d', model_name, w_idx), ...
        'Position', [1565, 500 + 22*w_idx, 1585, 515 + 22*w_idx], ...
        'FilteringAndDerivatives', 'filter', ...
        'SimscapeFilterOrder', '1', ...
        'InputFilterTimeConstant', '0.001');
    ph_sl2ps_w = get_param(b_sl2ps_w, 'PortHandles');
    add_line(model_name, ph_demux_w.Outport(w_idx), ph_sl2ps_w.Inport(1));
    add_line(model_name, ph_sl2ps_w.RConn(1), ph_torso_6dof.LConn(w_idx + 1));
end

% Demux 3D Vacuum Suction Force into Payload_6DOF LConn(2..4) [Fx, Fy, Fz]
b_demux_suc = add_block('simulink/Commonly Used Blocks/Demux', ...
    [model_name '/Demux_Suction_Force'], ...
    'Position', [1530, 630, 1535, 700], ...
    'Outputs', '3');
ph_demux_suc = get_param(b_demux_suc, 'PortHandles');
add_line(model_name, ph_wbc.Outport(8), ph_demux_suc.Inport(1));

for s_idx = 1:3
    b_sl2ps_s = add_block('nesl_utility/Simulink-PS Converter', ...
        sprintf('%s/SL2PS_SuctionForce_%d', model_name, s_idx), ...
        'Position', [1565, 615 + 22*s_idx, 1585, 630 + 22*s_idx], ...
        'FilteringAndDerivatives', 'filter', ...
        'SimscapeFilterOrder', '1', ...
        'InputFilterTimeConstant', '0.001');
    ph_sl2ps_s = get_param(b_sl2ps_s, 'PortHandles');
    add_line(model_name, ph_demux_suc.Outport(s_idx), ph_sl2ps_s.Inport(1));
    add_line(model_name, ph_sl2ps_s.RConn(1), ph_box_6dof.LConn(s_idx + 1));
end

% Log all WBC outputs to workspace
b_out_tau = add_block('simulink/Sinks/To Workspace', ...
    [model_name '/ToWS_Leg_Torques'], 'Position', [1620, 80, 1695, 105], ...
    'VariableName', 'sim_tau_legs', 'SaveFormat', 'Timeseries');
b_out_arm = add_block('simulink/Sinks/To Workspace', ...
    [model_name '/ToWS_Arm_Torques'], 'Position', [1620, 130, 1695, 155], ...
    'VariableName', 'sim_tau_arm', 'SaveFormat', 'Timeseries');
b_out_rpy = add_block('simulink/Sinks/To Workspace', ...
    [model_name '/ToWS_Torso_RPY'], 'Position', [1620, 180, 1695, 205], ...
    'VariableName', 'sim_torso_rpy', 'SaveFormat', 'Timeseries');
b_out_grf = add_block('simulink/Sinks/To Workspace', ...
    [model_name '/ToWS_F_GRF'], 'Position', [1620, 230, 1695, 255], ...
    'VariableName', 'sim_F_grf', 'SaveFormat', 'Timeseries');
b_out_cmask = add_block('simulink/Sinks/To Workspace', ...
    [model_name '/ToWS_Contact_Mask'], 'Position', [1620, 280, 1695, 305], ...
    'VariableName', 'sim_contact_mask', 'SaveFormat', 'Timeseries');
b_out_nav = add_block('simulink/Sinks/To Workspace', ...
    [model_name '/ToWS_Nav_Log'], 'Position', [1620, 330, 1695, 355], ...
    'VariableName', 'sim_nav_log', 'SaveFormat', 'Timeseries');
b_out_qarm = add_block('simulink/Sinks/To Workspace', ...
    [model_name '/ToWS_Arm_Angles'], 'Position', [1620, 380, 1695, 405], ...
    'VariableName', 'sim_q_arm', 'SaveFormat', 'Timeseries');
b_out_warm = add_block('simulink/Sinks/To Workspace', ...
    [model_name '/ToWS_Arm_Wrench'], 'Position', [1620, 430, 1695, 455], ...
    'VariableName', 'sim_w_arm', 'SaveFormat', 'Timeseries');
b_out_mlog = add_block('simulink/Sinks/To Workspace', ...
    [model_name '/ToWS_Mission_Log'], 'Position', [1620, 480, 1695, 505], ...
    'VariableName', 'sim_mission_log', 'SaveFormat', 'Timeseries');

add_line(model_name, ph_wbc.Outport(1),  get_param(b_out_tau,   'PortHandles').Inport(1));
add_line(model_name, ph_wbc.Outport(2),  get_param(b_out_arm,   'PortHandles').Inport(1));
add_line(model_name, ph_wbc.Outport(3),  get_param(b_out_rpy,   'PortHandles').Inport(1));
add_line(model_name, ph_wbc.Outport(4),  get_param(b_out_grf,   'PortHandles').Inport(1));
add_line(model_name, ph_wbc.Outport(5),  get_param(b_out_cmask, 'PortHandles').Inport(1));
add_line(model_name, ph_wbc.Outport(6),  get_param(b_out_nav,   'PortHandles').Inport(1));
add_line(model_name, ph_wbc.Outport(9),  get_param(b_out_qarm,  'PortHandles').Inport(1));
add_line(model_name, ph_wbc.Outport(10), get_param(b_out_warm,  'PortHandles').Inport(1));
add_line(model_name, ph_wbc.Outport(11), get_param(b_out_mlog,  'PortHandles').Inport(1));

save_system(model_name, mdl_path);
fprintf('Successfully wired Stage 3/4/5 WBC_Controller into: %s\n', mdl_path);
end
